-- Bootstrap the canonical identity table only on fresh databases. Existing
-- user IDs, password hashes and clinical records are retained.
CREATE TABLE IF NOT EXISTS public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

DO $$
DECLARE role_column SMALLINT; restriction RECORD;
BEGIN
    IF (SELECT count(*) FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
        AND column_name IN ('user_id','full_name','email','password_hash','role','is_active')) <> 6 THEN
        RAISE EXCEPTION 'Existing users table is incompatible; migrate its schema explicitly first';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
        AND column_name = 'role' AND data_type IN ('text','character varying')) THEN
        RAISE EXCEPTION 'Existing role type needs an explicit conversion before migration';
    END IF;
    SELECT attnum INTO role_column FROM pg_attribute
        WHERE attrelid = 'public.users'::regclass AND attname = 'role';
    -- Expand role-only CHECKs; never drop checks involving other fields.
    FOR restriction IN SELECT conname FROM pg_constraint
        WHERE conrelid = 'public.users'::regclass AND contype = 'c'
        AND conkey = ARRAY[role_column] LOOP
        EXECUTE format('ALTER TABLE public.users DROP CONSTRAINT %I', restriction.conname);
    END LOOP;
END $$;

ALTER TABLE public.users ADD CONSTRAINT medilink_users_role_check
    CHECK (role IN ('patient','doctor','receptionist','admin','auditor'));
-- Duplicate emails differing only by case must be resolved explicitly, not merged.
CREATE UNIQUE INDEX medilink_users_email_normalized_idx ON public.users(lower(email));

ALTER TABLE workflow_runs ADD COLUMN version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0);

CREATE TABLE workflow_creation_keys (
    owner_user_id TEXT NOT NULL,
    idempotency_key TEXT NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 128),
    fingerprint TEXT NOT NULL,
    workflow_id UUID NOT NULL REFERENCES workflow_runs(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (owner_user_id, idempotency_key)
);

CREATE TABLE workflow_action_keys (
    id UUID PRIMARY KEY,
    workflow_id UUID NOT NULL REFERENCES workflow_runs(id),
    action TEXT NOT NULL CHECK (length(btrim(action)) BETWEEN 1 AND 200),
    idempotency_key TEXT NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 128),
    fingerprint TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','succeeded','failed','uncertain')),
    result_reference TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (workflow_id, action, idempotency_key)
);

CREATE TABLE consumed_auth_stages (
    token_digest TEXT PRIMARY KEY,
    consumed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
